// Aliases for historical / alternate district names
const DISTRICT_ALIASES = {
  'aurangabad': 'Chhatrapati Sambhajinagar',
  'osmanabad': 'Dharashiv',
  'ahilyanagar': 'Ahmednagar',
};

/**
 * Normalizes a district name to its canonical key in MAHARASHTRA_LOCATIONS.
 */
export const normalizeDistrict = (district) => {
  if (!district) return '';
  const trimmed = district.trim();
  if (MAHARASHTRA_LOCATIONS[trimmed]) return trimmed;
  const lower = trimmed.toLowerCase();
  if (DISTRICT_ALIASES[lower]) return DISTRICT_ALIASES[lower];
  const found = Object.keys(MAHARASHTRA_LOCATIONS).find(
    (d) => d.toLowerCase() === lower
  );
  return found || trimmed;
};

/**
 * Returns available districts for the selected state.
 */
export const getDistrictsForState = (state) => {
  if (state === 'Maharashtra') {
    return Object.keys(MAHARASHTRA_LOCATIONS).sort();
  }
  return [];
};

/**
 * Returns available talukas for the selected state and district.
 */
export const getTalukasForDistrict = (state, district) => {
  if (state !== 'Maharashtra' || !district) return [];
  const canonical = normalizeDistrict(district);
  const talukas = MAHARASHTRA_LOCATIONS[canonical];
  return talukas ? [...talukas].sort() : [];
};
