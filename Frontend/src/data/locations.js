/**
 * Returns available districts for a selected state or UT.
 */
export const getDistrictsForState = (state) => {
  if (!state || !INDIA_LOCATIONS[state]) return [];
  return Object.keys(INDIA_LOCATIONS[state].districts).sort();
};

/**
 * Returns the proper regional administrative term for sub-district level
 * (e.g. 'Taluka', 'Tehsil', 'Mandal', 'Circle', 'Subdivision', etc.)
 */
export const getSubDistrictTermForState = (state) => {
  if (!state || !INDIA_LOCATIONS[state]) return 'Taluka / Tehsil';
  return INDIA_LOCATIONS[state].term || 'Sub-district';
};

/**
 * Normalizes district names across historical variations.
 */
export const normalizeDistrict = (state, district) => {
  if (!district) return '';
  const trimmed = district.trim();
  const currentDistricts = getDistrictsForState(state || 'Maharashtra');
  if (currentDistricts.includes(trimmed)) return trimmed;

  const lower = trimmed.toLowerCase();
  const found = currentDistricts.find((d) => d.toLowerCase() === lower);
  if (found) return found;

  // Common historical aliases
  if (/aurangabad/i.test(trimmed)) {
    const cs = currentDistricts.find((d) => /Chhatrapati Sambhajinagar/i.test(d));
    if (cs) return cs;
  }
  if (/osmanabad/i.test(trimmed)) {
    const dh = currentDistricts.find((d) => /Dharashiv/i.test(d));
    if (dh) return dh;
  }
  if (/ahmednagar|ahilyanagar/i.test(trimmed)) {
    const ah = currentDistricts.find((d) => /Ahmednagar/i.test(d));
    if (ah) return ah;
  }
  return trimmed;
};

/**
 * Returns available sub-districts (talukas/tehsils/mandals) for the selected district.
 */
export const getSubDistrictsForDistrict = (state, district) => {
  if (!state || !district || !INDIA_LOCATIONS[state]) return [];
  const stateData = INDIA_LOCATIONS[state];
  const canonical = normalizeDistrict(state, district);
  const subs = stateData.districts[canonical];
  return subs ? [...subs].sort() : [];
};

// Backward-compatibility alias
export const getTalukasForDistrict = (state, district) => {
  return getSubDistrictsForDistrict(state, district);
};

